function row(id: string, state: ConvergenceClaim["state"]): ConvergenceClaim {
	return { id, version: 1, scope: {}, claim: `Claim ${id}.`, evidence_refs: [], state };
}

function messagesWithCitation(line: string): LiveContextMessage[] {
	return [
		{ role: "user", content: "Do the thing.", timestamp: 1 },
		{ role: "assistant", content: [{ type: "text", text: `Working.\n${line}\nDone.` }], stopReason: "stop", timestamp: 2 },
	];
}

function renderWithRows(line: string, rows: ConvergenceClaim[]): ContextDocumentSnapshot {
	return renderContextDocument(messagesWithCitation(line), {
		revision: 0,
		documentSeed: "suspect-seed",
		claimsBody: renderClaimsBody(selectActiveClaims(rows.filter((row) => row.state === "ACTIVE"))),
		claimsMeta: { rows, root: join(tmpdir(), ".convergence") },
	});
}

const options: ApplyDocumentOptions = { editingMode: "clm", projectDir: tmpdir() };

describe("reconcileSuspectMarkers", () => {
	test("ACTIVE rows leave citations alone; SUSPECT rows gain the marker", () => {
		const body = "Working.\nOBSERVED: steady@1\nOBSERVED: flip@1\nDone.";
		const out = reconcileSuspectMarkers(body, [row("steady", "ACTIVE"), row("flip", "SUSPECT")]);
		expect(out.body).toBe(`Working.\nOBSERVED: steady@1\nOBSERVED: flip@1${SUSPECT_MARKER}\nDone.`);
		expect(out.marked).toEqual(["flip@1"]);
		expect(out.unmarked).toEqual([]);
	});

	test("re-authorized claims lose the marker; unknown claims are untouched", () => {
		const body = `OBSERVED: back@1${SUSPECT_MARKER}\nOBSERVED: gone@1\nOBSERVED: notes.txt:2\nASSUMED: hunch\n(see OBSERVED: back@1)`;
		const out = reconcileSuspectMarkers(body, [row("back", "ACTIVE")]);
		expect(out.body).toBe("OBSERVED: back@1\nOBSERVED: gone@1\nOBSERVED: notes.txt:2\nASSUMED: hunch\n(see OBSERVED: back@1)");
		expect(out.unmarked).toEqual(["back@1"]);
	});

	test("already-marked SUSPECT lines are stable (idempotent)", () => {
		const body = `OBSERVED: flip@1${SUSPECT_MARKER}`;
		const out = reconcileSuspectMarkers(body, [row("flip", "SUSPECT")]);
		expect(out.body).toBe(body);
		expect(out.marked).toEqual([]);
	});
});

describe("diffClaimStates", () => {
	test("reports only changed keys, sorted", () => {
		const previous = new Map([["a@1", "ACTIVE"], ["b@1", "ACTIVE"], ["c@1", "SUSPECT"]]);
		const current = new Map([["a@1", "SUSPECT"], ["b@1", "ACTIVE"], ["c@1", "ACTIVE"], ["d@1", "ACTIVE"]]);
		expect(diffClaimStates(previous, current)).toEqual([
			{ key: "a@1", from: "ACTIVE", to: "SUSPECT" },
			{ key: "c@1", from: "SUSPECT", to: "ACTIVE" },
		]);
	});
});

describe("marker in the rendered mirror", () => {
	test("ACTIVE → SUSPECT gains [SUSPECT]; SUSPECT → ACTIVE removes it", () => {
		const before = renderWithRows("OBSERVED: flip@1", [row("steady", "ACTIVE"), row("flip", "ACTIVE")]);
		expect(before.text).toContain("OBSERVED: flip@1\n");
		expect(before.text).not.toContain(SUSPECT_MARKER);
		const after = renderWithRows("OBSERVED: flip@1", [row("steady", "ACTIVE"), row("flip", "SUSPECT")]);
		expect(after.text).toContain(`OBSERVED: flip@1${SUSPECT_MARKER}`);
		const reauth = renderWithRows(`OBSERVED: flip@1${SUSPECT_MARKER}`, [row("flip", "ACTIVE")]);
		expect(reauth.text).toContain("OBSERVED: flip@1\n");
		expect(reauth.text).not.toContain(SUSPECT_MARKER);
	});

	test("uncited SUSPECT claims leave the mirror otherwise unchanged", () => {
		const plain = renderWithRows("No citations here.", [row("flip", "ACTIVE")]);
		const challenged = renderWithRows("No citations here.", [row("flip", "SUSPECT")]);
		expect(challenged.text).not.toContain(SUSPECT_MARKER);
		// Only the claims body (regenerated by Phase 1) differs, not the message blocks.
		expect(challenged.blocks.map((block) => block.body)).toEqual(plain.blocks.map((block) => block.body));
	});

	test("two claims move in the same render; both citations update", () => {
		const snapshot = renderWithRows("X", [row("a", "SUSPECT"), row("b", "SUSPECT")]);
		const cited = renderContextDocument(
			[{ role: "user", content: "t", timestamp: 1 }, {
				role: "assistant",
				content: [{ type: "text", text: "OBSERVED: a@1\nOBSERVED: b@1" }],
				stopReason: "stop",
				timestamp: 2,
			}],
			{
				revision: 0,
				documentSeed: "two-seed",
				claimsBody: renderClaimsBody([]),
				claimsMeta: { rows: [row("a", "SUSPECT"), row("b", "SUSPECT")], root: join(tmpdir(), ".convergence") },
			},
		);
		expect(cited.text).toContain(`OBSERVED: a@1${SUSPECT_MARKER}`);
		expect(cited.text).toContain(`OBSERVED: b@1${SUSPECT_MARKER}`);
		expect(snapshot.text).not.toContain("OBSERVED: a@1");
	});

	test("the claims region itself carries no OBSERVED: marker lines", () => {
		const snapshot = renderWithRows("OBSERVED: flip@1", [row("flip", "SUSPECT")]);
		const claimsBlock = snapshot.text.split("[[CTX_TURN").find((part) => part.includes("id=claims ")) ?? "";
		// The head teaches the format inline, but no whole line is a citation.
		expect(claimsBlock.split("\n").some((line) => parseCitationLine(line) !== undefined)).toBe(false);
	});

	test("self-validation: a synthetic transition produces a confined non-zero rewrite", () => {
		const line = "OBSERVED: flip@1";
		const before = renderWithRows(line, [row("flip", "ACTIVE")]);
		const after = renderWithRows(line, [row("flip", "SUSPECT")]);
		expect(after.text).not.toBe(before.text);
		const beforeLines = before.text.split("\n");
		const afterLines = after.text.split("\n");
		const changed = afterLines.filter((text, index) => text !== beforeLines[index]);
		// The marker line, plus the claims body Phase 1 regenerates from the fold.
		expect(changed).toContain(`OBSERVED: flip@1${SUSPECT_MARKER}`);
		expect(changed.filter((text) => !text.startsWith("- "))).toEqual([`OBSERVED: flip@1${SUSPECT_MARKER}`]);
	});
});

describe("marked citations at the gate (Phase 2 × Phase 3)", () => {
	function suspectSnapshot(): ContextDocumentSnapshot {
		return renderWithRows("OBSERVED: flip@1", [row("flip", "SUSPECT")]);
	}

	test("marked line kept verbatim is past reasoning: accepted", () => {
		const snapshot = suspectSnapshot();
		expect(snapshot.text).toContain(`OBSERVED: flip@1${SUSPECT_MARKER}`);
		const result = applyContextDocument(snapshot.text, snapshot, options);
		expect(result.accepted).toBe(true);
	});

	test("marked line in edited text is new reliance: rejected", () => {
		const snapshot = suspectSnapshot();
		const edited = snapshot.text.replace(`OBSERVED: flip@1${SUSPECT_MARKER}`, `OBSERVED: flip@1${SUSPECT_MARKER}\nMore work.`);
		const result = applyContextDocument(edited, snapshot, options);
		expect(result.accepted).toBe(false);
		expect(result.reason).toMatch(/state/);
	});

	test("hand-stripping the marker does not re-authorize: rejected", () => {
		const snapshot = suspectSnapshot();
		const stripped = snapshot.text.replace(SUSPECT_MARKER, "");
		const result = applyContextDocument(stripped, snapshot, options);
		expect(result.accepted).toBe(false);
		expect(result.reason).toMatch(/SUSPECT/);
	});

	test("fresh plain citation of a SUSPECT claim is rejected (Phase 2)", () => {
		const snapshot = renderWithRows("Nothing cited.", [row("flip", "SUSPECT")]);
		const result = applyContextDocument(`${snapshot.text}\nOBSERVED: flip@1\n`, snapshot, options);
		expect(result.accepted).toBe(false);
		expect(result.reason).toMatch(/state/);
	});
});

describe("loader causes and the panel claims page", () => {
	async function storeWithChallenge(): Promise<{ root: string; cause: string | undefined }> {
		const proj = mkdtempSync(join(tmpdir(), "clm-suspect-"));
		const conv = join(proj, ".convergence");
		mkdirSync(join(conv, "rules"), { recursive: true });
		writeFileSync(join(conv, "rules", "flip.json"), JSON.stringify({ id: "flip", version: 1, scope: {}, claim: "Flip.", evidence_refs: [] }));
		const events = [
			{ event: "CANDIDATE", id: "flip", version: 1 },
			{ event: "AUTHORIZED", id: "flip", version: 1, approval_ref: "human:br" },
			{ event: "ACTIVE", id: "flip", version: 1 },
			{ event: "CHALLENGE", id: "flip", version: 1, counterevidence_ref: "evidence/bug.md" },
		];
		writeFileSync(join(conv, "transitions.jsonl"), events.map((line) => JSON.stringify(line)).join("\n") + "\n");
		const store = await loadConvergenceStore(conv);
		return { root: conv, cause: store?.causes["flip@1"] };
	}

	test("the latest CHALLENGE counterevidence is recorded as the cause", async () => {
		const { cause } = await storeWithChallenge();
		expect(cause).toBe("evidence/bug.md");
	});

	test("buildClaims groups cited+SUSPECT first with transitions", () => {
		const model = buildClaims({
			claims: {
				version: 1,
				at: "2026-01-01T00:00:00.000Z",
				revision: 3,
				root: "/proj/.convergence",
				digest: "abc",
				injected: [
					{ id: "flip", version: 1, state: "SUSPECT", scope: {}, claim: "Flip.", evidence_refs: [], approval_ref: "human:br" },
					{ id: "steady", version: 1, state: "ACTIVE", scope: {}, claim: "Steady.", evidence_refs: [] },
				],
				cited: [{ key: "flip@1", line: 12, marked: true }],
				transitions: [{ key: "flip@1", from: "ACTIVE", to: "SUSPECT", at: "2026-01-01T00:00:01.000Z", cause: "evidence/bug.md" }],
			},
		});
		expect(model?.injected).toHaveLength(2);
		const flip = model?.injected.find((row) => row.key === "flip@1");
		expect(flip).toMatchObject({ state: "SUSPECT", citedAt: [12], marked: true });
		expect(flip?.transition).toMatchObject({ from: "ACTIVE", to: "SUSPECT", cause: "evidence/bug.md" });
		const page = claimsPage({ ...richModel(), claims: model! }, 72).map(plain).join("\n");
		expect(page).toContain("Cited and now SUSPECT");
		expect(page).toContain("flip@1");
		expect(page).toContain("evidence/bug.md");
	});

	test("no store means an empty claims page, not a crash", () => {
		expect(buildClaims({ claims: undefined })).toBeUndefined();
		const page = claimsPage({ ...richModel(), claims: undefined }, 72).map(plain).join("\n");
		expect(page).toContain("No claim store");
	});
});

describe("end to end across two transforms", () => {
	test("a challenge between requests marks the citation, logs the transition, writes claims.json", async () => {
		const proj = mkdtempSync(join(tmpdir(), "clm-suspect-e2e-"));
		const conv = join(proj, ".convergence");
		mkdirSync(join(conv, "rules"), { recursive: true });
		writeFileSync(join(conv, "rules", "flip.json"), JSON.stringify({ id: "flip", version: 1, scope: {}, claim: "Flip.", evidence_refs: [] }));
		const lifecycle = (extra: Array<Record<string, unknown>> = []) =>
			[
				{ event: "CANDIDATE", id: "flip", version: 1 },
				{ event: "AUTHORIZED", id: "flip", version: 1, approval_ref: "human:br" },
				{ event: "ACTIVE", id: "flip", version: 1 },
				...extra,
			].map((line) => JSON.stringify(line)).join("\n") + "\n";
		writeFileSync(join(conv, "transitions.jsonl"), lifecycle());

		const clm = await ClmSession.open(SESSION, settings({ convergenceDir: conv }));
		const raw = [
			{ ...user("msg_u1", "Inspect the repository and report.") },
			assistant("msg_a1", "Looking."),
			user("msg_u2", "Note.\nOBSERVED: flip@1"),
		];
		await clm.transform(structuredClone(raw));
		const first = readFileSync(clm.mirrorPath, "utf8");
		expect(first).toContain("OBSERVED: flip@1");
		expect(first).not.toContain(SUSPECT_MARKER);

		appendFileSync(join(conv, "transitions.jsonl"), JSON.stringify({ event: "CHALLENGE", id: "flip", version: 1, counterevidence_ref: "evidence/bug.md" }) + "\n");
		await clm.transform([...structuredClone(raw), user("msg_u3", "Continue.")]);
		const second = readFileSync(clm.mirrorPath, "utf8");
		expect(second).toContain(`OBSERVED: flip@1${SUSPECT_MARKER}`);

		const claims = JSON.parse(readFileSync(join(clm.store.directory, "claims.json"), "utf8")) as {
			injected: Array<{ id: string; state: string }>;
			cited: Array<{ key: string; marked: boolean }>;
			transitions: Array<{ key: string; from: string; to: string; at: string; cause?: string }>;
		};
		expect(claims.injected.find((row) => row.id === "flip")?.state).toBe("SUSPECT");
		expect(claims.cited.find((row) => row.key === "flip@1")?.marked).toBe(true);
		expect(claims.transitions).toContainEqual({ key: "flip@1", from: "ACTIVE", to: "SUSPECT", at: expect.any(String), cause: "evidence/bug.md" });
		const events = readFileSync(join(clm.store.directory, "events.jsonl"), "utf8");
		expect(events).toContain('"event":"convergence-transition"');
	});
});
